-- Statement-level BEFORE triggers act on a superuser too, so a stray write
-- from the boards app (it connects as the superuser t_boards) fails. The check
-- is on session_user: SET ROLE oq_console from another login does not pass.
-- A full pg_restore loads data before it creates triggers; a data-only
-- restore of oq needs --disable-triggers (spec §5.7).
CREATE FUNCTION "oq"."refuse_other_writers"() RETURNS trigger
	LANGUAGE plpgsql SECURITY INVOKER AS $$
BEGIN
	IF session_user <> 'oq_console' THEN
		RAISE EXCEPTION 'oq.%: only oq_console writes the owner queue, not %', TG_TABLE_NAME, session_user
			USING ERRCODE = 'insufficient_privilege';
	END IF;
	RETURN NULL;
END
$$;--> statement-breakpoint
ALTER FUNCTION "oq"."refuse_other_writers"() OWNER TO oq_owner;--> statement-breakpoint
CREATE TRIGGER "oq_docs_writer" BEFORE INSERT OR UPDATE OR DELETE OR TRUNCATE ON "oq"."docs"
	FOR EACH STATEMENT EXECUTE FUNCTION "oq"."refuse_other_writers"();--> statement-breakpoint
CREATE TRIGGER "oq_events_writer" BEFORE INSERT OR UPDATE OR DELETE OR TRUNCATE ON "oq"."events"
	FOR EACH STATEMENT EXECUTE FUNCTION "oq"."refuse_other_writers"();--> statement-breakpoint
CREATE TRIGGER "oq_files_writer" BEFORE INSERT OR UPDATE OR DELETE OR TRUNCATE ON "oq"."files"
	FOR EACH STATEMENT EXECUTE FUNCTION "oq"."refuse_other_writers"();
