#!/usr/bin/env python3
"""Git and GitHub steps of the daily evolution run (`daily.py`): its own worktree, versions of a file, a commit
built without a checkout, pull requests and the merge gate.

Nothing here touches a person's checkout. A commit is built from the base commit's tree in a temporary index
(`GIT_INDEX_FILE`), so a revert or a verdict commit needs no working tree and never moves anyone's HEAD. The merge
gate is the only place that merges, and it merges only what `merge_allowed` and `checks_green` let through. Stdlib
only.
"""
import fnmatch
import json
import os
import subprocess
import tempfile

# Pull requests the run may merge by itself: these paths only, and never one from NEVER_MERGE (the guard's own
# code, settings and CI, which automation must not be able to rewrite). A skill with mirrors in other harnesses
# (`.agents/skills/<name>`) is excluded too: its mirrors are regenerated by `sync-agent-skills.sh`, not here.
AUTO_MERGE_PATHS = (
    '.claude/skills/*/SKILL.md',
    '.claude/rules/*.md',
    '.claude/agents/*.md',
    '.claude/commands/*.md',
    'eval/prompts/*.md',
    'eval/prompts/*/*.md',
    'process/prompts/*.md',
    'eval/pipeline/genome/antigens.json',
    'eval/pipeline/reflex/test_reflex.py',  # the antigens' own test
    'eval/evolve/cases/*.jsonl',
    'eval/evolve/verdicts.jsonl',
)
NEVER_MERGE = (
    '.claude/hooks/*', '.claude/scripts/*', '.claude/settings*.json', '.claude/merge-guard*', '.github/*',
    'eval/evolve/*.py', 'eval/evolve/*.sh', 'eval/evolve/budget.json', '*.plist',
)
BRANCH_PREFIX = 'evolve/'
MAX_MERGE_FILES = 12


def git(repo, *args, env=None, check=True, data=None):
    out = subprocess.run(['git', '-C', repo, *args], capture_output=True, text=True, input=data,
                         env=dict(os.environ, **env) if env else None)
    if check and out.returncode != 0:
        raise RuntimeError('git %s: %s' % (' '.join(args[:3]), out.stderr.strip()[:300]))
    return out.stdout if out.returncode == 0 else None


def main_repo(path):
    """The repository's main checkout (where `.git` lives), from any of its worktrees."""
    common = git(path, 'rev-parse', '--path-format=absolute', '--git-common-dir').strip()
    return os.path.dirname(common)


def fetch(repo, base):
    git(repo, 'fetch', '--quiet', 'origin', base)
    return git(repo, 'rev-parse', 'origin/%s' % base).strip()


def refresh_worktree(repo, rel, base):
    """The run's own worktree, detached on a fresh `origin/<base>`; created when missing. Returns its HEAD."""
    head = fetch(repo, base)
    path = os.path.join(repo, rel)
    if not os.path.isdir(path):
        git(repo, 'worktree', 'add', '--quiet', '--detach', path, head)
    else:
        git(path, 'checkout', '--quiet', '--force', '--detach', head)
        git(path, 'clean', '-fdq')  # untracked leftovers of a session; ignored runtime files stay
    return head


def since_day_ago(repo, base):
    """The base as it was 24 hours ago: the first run's baseline when no state is kept yet."""
    out = git(repo, 'rev-list', '-1', '--before=24 hours ago', 'origin/%s' % base, check=False)
    return (out or '').strip() or git(repo, 'rev-parse', 'origin/%s~1' % base).strip()


def short(repo, rev):
    return git(repo, 'rev-parse', '--short', rev).strip()


def changed_files(repo, since, head):
    return [p for p in git(repo, 'diff', '--name-only', since, head).splitlines() if p]


def file_at(repo, rev, path):
    """The file's text at a revision, or None when it does not exist there."""
    return git(repo, 'show', '%s:%s' % (rev, path), check=False)


def last_commit_of(repo, rev, path):
    out = git(repo, 'log', '-1', '--format=%h %s', rev, '--', path, check=False)
    return (out or '').strip()


def commit_files(repo, parent, files, message):
    """A commit on top of `parent` whose tree is the parent's with `files` ({path: text}) replaced. Built in a
    temporary index: no checkout, no HEAD moves."""
    fd, index = tempfile.mkstemp(prefix='evolve-index-')
    os.close(fd)
    os.unlink(index)  # git creates it; an empty file is not a valid index
    env = {'GIT_INDEX_FILE': index}
    try:
        git(repo, 'read-tree', parent, env=env)
        for path, text in sorted(files.items()):
            blob = git(repo, 'hash-object', '-w', '--stdin', data=text).strip()
            git(repo, 'update-index', '--add', '--cacheinfo', '100644,%s,%s' % (blob, path), env=env)
        tree = git(repo, 'write-tree', env=env).strip()
        return git(repo, 'commit-tree', tree, '-p', parent, '-F', '-', data=message).strip()
    finally:
        if os.path.exists(index):
            os.unlink(index)


def gh(repo, *args, check=True):
    out = subprocess.run(['gh', *args], capture_output=True, text=True, cwd=repo)
    if check and out.returncode != 0:
        raise RuntimeError('gh %s: %s' % (' '.join(args[:3]), (out.stderr or out.stdout).strip()[:300]))
    return out.stdout


def open_pr(repo, base, commit, branch, title, body):
    """Push `commit` as `branch` and open a pull request into `base`. Returns its URL."""
    git(repo, 'push', '--quiet', 'origin', '%s:refs/heads/%s' % (commit, branch))
    return gh(repo, 'pr', 'create', '--base', base, '--head', branch, '--title', title, '--body', body).strip()


def mirrored(repo, rev, path):
    """A skill that other harnesses mirror: its mirrors change with it, which this run does not do."""
    parts = path.split('/')
    if len(parts) == 4 and parts[:2] == ['.claude', 'skills']:
        return file_at(repo, rev, '.agents/skills/%s/SKILL.md' % parts[2]) is not None
    return False


def merge_allowed(files, repo=None, rev=None):
    """(ok, why): every file is on AUTO_MERGE_PATHS, none on NEVER_MERGE, no mirrored skill, not too many."""
    if not files:
        return False, 'no files'
    if len(files) > MAX_MERGE_FILES:
        return False, '%d files (at most %d)' % (len(files), MAX_MERGE_FILES)
    for path in files:
        if any(fnmatch.fnmatchcase(path, p) for p in NEVER_MERGE):
            return False, '%s is never merged by the run' % path
        if not any(fnmatch.fnmatchcase(path, p) and path.count('/') == p.count('/') for p in AUTO_MERGE_PATHS):
            return False, '%s is not on the auto-merge list' % path
        if repo and rev and mirrored(repo, rev, path):
            return False, '%s has mirrors (sync-agent-skills.sh)' % path
    return True, 'paths on the list'


def checks_green(checks):
    """(ok, why) from `gh pr checks --json name,bucket`: at least one check, every one passed or skipped."""
    if not checks:
        return False, 'no checks ran'
    bad = [c['name'] for c in checks if c.get('bucket') not in ('pass', 'skipping')]
    if bad:
        return False, 'not green: %s' % ', '.join(sorted(bad))
    if not any(c.get('bucket') == 'pass' for c in checks):
        return False, 'every check skipped'
    return True, '%d checks green' % len(checks)


def superseded(verdicts, body):
    """A revert PR whose verdict was later marked brak (a session review) must not merge."""
    marker = 'evolve-verdict: '
    vid = next((ln.split(marker, 1)[1].strip() for ln in (body or '').splitlines() if marker in ln), None)
    return bool(vid) and any(v.get('supersedes') == vid and v.get('status') != 'accepted' for v in verdicts)


def merge_ready(repo, base, verdicts, enabled, dry=False):
    """Merge the run's own open PRs (branches `evolve/…`) that pass the path list and have green checks, through
    `gh pr merge --auto --match-head-commit`. Off (`evolveAutoMerge`) — report only. Returns one row per PR."""
    raw = gh(repo, 'pr', 'list', '--base', base, '--state', 'open', '--limit', '50',
             '--json', 'number,headRefName,headRefOid,files,isDraft,body,url')
    rows = []
    for pr in json.loads(raw or '[]'):
        if not pr['headRefName'].startswith(BRANCH_PREFIX) or pr.get('isDraft'):
            continue
        row = {'pr': pr['url'], 'branch': pr['headRefName']}
        files = [f['path'] for f in pr.get('files') or []]
        ok, why = merge_allowed(files, repo, pr['headRefOid'])
        if ok and superseded(verdicts, pr.get('body')):
            ok, why = False, 'its verdict was marked brak later'
            if not dry:
                gh(repo, 'pr', 'close', str(pr['number']), '--comment', 'evolve: the verdict behind this PR was '
                   'marked brak on review — closed, nothing applied.', check=False)
        if ok:
            checks = json.loads(gh(repo, 'pr', 'checks', str(pr['number']), '--json', 'name,bucket',
                                   check=False) or '[]')
            ok, why = checks_green(checks)
        if ok and not enabled:
            ok, why = False, 'evolveAutoMerge is off — waits for a person'
        if ok and dry:
            ok, why = False, 'would merge (dry run)'
        elif ok:
            out = subprocess.run(['gh', 'pr', 'merge', str(pr['number']), '--auto', '--squash', '--delete-branch',
                                  '--match-head-commit', pr['headRefOid']], capture_output=True, text=True, cwd=repo)
            ok = out.returncode == 0
            why = 'merged (auto)' if ok else 'gh refused: %s' % (out.stderr or out.stdout).strip()[:200]
        row.update(merged=ok, why=why)
        rows.append(row)
    return rows
